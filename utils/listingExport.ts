/**
 * Exports listing text in fastlane's metadata layout, which Flutter and React Native
 * release pipelines commonly use (fastlane deliver / supply):
 *
 *   fastlane/metadata/<apple-locale>/{name,subtitle,promotional_text,description,keywords,release_notes}.txt
 *   fastlane/metadata/android/<play-locale>/{title,short_description,full_description}.txt
 */
import JSZip from "jszip";
import { FIELDS, type Listing } from "./listingRules";
import type { Locale } from "./presets";
import { storeLocale } from "./languages";

export function fastlaneFiles(drafts: Record<Locale, Listing>): { path: string; text: string }[] {
  const files: { path: string; text: string }[] = [];
  for (const [locale, listing] of Object.entries(drafts) as [Locale, Listing][]) {
    if (!listing) continue;
    for (const f of FIELDS) {
      const text = listing[f.id].trim();
      if (!text) continue;
      const dir = f.store === "apple" ? `fastlane/metadata/${storeLocale("app_store", locale)}` : `fastlane/metadata/android/${storeLocale("play_store", locale)}`;
      files.push({ path: `${dir}/${f.fastlane}`, text: `${text}\n` });
    }
  }
  return files;
}

export async function buildFastlaneZip(drafts: Record<Locale, Listing>): Promise<Blob> {
  const files = fastlaneFiles(drafts);
  if (!files.length) throw new Error("Nothing to export yet. Fill in at least one field.");
  const zip = new JSZip();
  for (const f of files) zip.file(f.path, f.text);
  zip.file(
    "README.md",
    `# Store listing text\n\nGenerated by StoreReady. Copy the \`fastlane\` folder into your project (for Flutter, into \`ios/\` and \`android/\`, or the repo root, wherever your Fastfile lives).\n\n- iOS: \`fastlane deliver\` reads \`fastlane/metadata/<locale>/\`\n- Android: \`fastlane supply\` reads \`fastlane/metadata/android/<locale>/\`\n`,
  );
  return zip.generateAsync({ type: "blob" });
}
